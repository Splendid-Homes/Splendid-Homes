// One-off: converts the approved prototype's sample data (prototype/assets/shared/data.js)
// into typed mock data for the Next.js build. Run: node scripts/port-data.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = fs.readFileSync(path.join(root, '../prototype/assets/shared/data.js'), 'utf8');
const ctx = { window: {} };
vm.runInNewContext(src, ctx);
const seed = ctx.window.SH_SEED;

const slugify = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const withSlug = (list, key) => list.map(x => ({ slug: slugify(x[key]), ...x }));

const data = {
  properties: withSlug(seed.properties, 'title'),
  projects: withSlug(seed.projects, 'name'),
  communities: seed.communities,
  developers: seed.developers,
  agents: withSlug(seed.agents, 'name'),
  posts: withSlug(seed.posts, 'title'),
  testimonials: seed.testimonials,
  services: seed.services,
  careers: seed.careers,
  settings: seed.settings,
};

const out = `// AUTO-GENERATED by scripts/port-data.mjs from the approved prototype's sample data.
// Placeholder content until the CMS is connected. Do not edit by hand.
import type { Agent, Career, Community, Developer, Post, Project, Property, Service, SiteSettings, Testimonial } from './types';

export const properties: Property[] = ${JSON.stringify(data.properties, null, 2)};

export const projects: Project[] = ${JSON.stringify(data.projects, null, 2)};

export const communities: Community[] = ${JSON.stringify(data.communities, null, 2)};

export const developers: Developer[] = ${JSON.stringify(data.developers, null, 2)};

export const agents: Agent[] = ${JSON.stringify(data.agents, null, 2)};

export const posts: Post[] = ${JSON.stringify(data.posts, null, 2)};

export const testimonials: Testimonial[] = ${JSON.stringify(data.testimonials, null, 2)};

export const services: Service[] = ${JSON.stringify(data.services, null, 2)};

export const careers: Career[] = ${JSON.stringify(data.careers, null, 2)};

export const settings: SiteSettings = ${JSON.stringify(data.settings, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src/data/mock.ts'), out);
console.log('wrote src/data/mock.ts', Object.fromEntries(Object.entries(data).map(([k, v]) => [k, Array.isArray(v) ? v.length : 'obj'])));
